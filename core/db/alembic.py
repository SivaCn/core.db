# A Schema stores all the configuration and business tables other than transactional ones.
BASE_SCHEMA = 'base_schema'


@compiles(CreateColumn, 'postgresql')
def use_identity(element, compiler, **kwargs):

    return compiler.visit_create_column(
        element, **kwargs
    ).replace("SERIAL", "INT GENERATED BY DEFAULT AS IDENTITY")


def utc_now():
    """Helper function to ensure UTC datetime."""
    return datetime.now(pytz.utc)


def field_unique_id():
    """Helper function for common unique_id field fro table creation."""
    return sa.Column(
        'unique_id',
        UUID(as_uuid=True),
        unique=True,
        nullable=False,
        server_default=sa.text("gen_random_uuid()")
    )

def field_is_active():
    """Helper function for common is_active field fro table creation."""
    return sa.Column('is_active', sa.String(1), nullable=False)


def field_created_date():
    """Helper function for common created_date field fro table creation."""
    return sa.Column(
        'created_date',
        sa.DateTime(timezone=False),
        nullable=False,
        server_default=sa.text("TIMEZONE('UTC', now())")
    )


def field_updated_date():
    """Helper function for common updated_date field fro table creation."""
    return sa.Column(
        'updated_date',
        sa.DateTime(timezone=False),
        nullable=False,
        server_default=sa.text("TIMEZONE('UTC', now())"),
        onupdate=utc_now
    )

